# frozen_string_literal: true

require "fileutils"

module Rails2qdbd
  # Writes converter results to disk, or reports how the disk differs (for --check).
  # Only files starting with the generated header are ever replaced or removed.
  module Output
    module_function

    # path: a .txt file (single result file) or a directory. Returns the paths actually written.
    # Raises Error, writing nothing, when a destination exists without the generated header.
    def write(result, path)
      foreign = planned(result, path).keys.select { |file| File.exist?(file) && !generated?(file) }
      if foreign.any?
        raise Error, "not generated by rails2qdbd, left untouched (move or delete them to regenerate): #{foreign.join(', ')}"
      end

      planned(result, path).filter_map do |file, text|
        next if File.file?(file) && File.read(file) == text

        FileUtils.mkdir_p(File.dirname(file))
        File.write(file, text)
        file
      end.tap { leftovers(result, path).each { |file| File.delete(file) } }
    end

    # Human-readable list of differences; empty means up to date.
    def stale(result, path)
      problems = planned(result, path).filter_map do |file, text|
        if !File.file?(file) then "#{file} (missing)"
        elsif !generated?(file) then "#{file} (not generated by rails2qdbd)"
        elsif File.read(file) != text then "#{file} (out of date)"
        end
      end
      problems + leftovers(result, path).map { |file| "#{file} (no longer generated)" }
    end

    def planned(result, path)
      return { path => result.files.values.first } if single_file?(path)

      result.files.sort.to_h { |name, text| [File.join(path, name), text] }
    end

    # Generated files in the output directory that this result no longer produces.
    def leftovers(result, path)
      return [] if single_file?(path) || !File.directory?(path)

      Dir.glob("*.txt", base: path).sort.filter_map do |name|
        file = File.join(path, name)
        file if !result.files.key?(name) && generated?(file)
      end
    end

    def generated?(file) = File.file?(file) && File.foreach(file).first.to_s.start_with?(Writer::HEADER)

    def single_file?(path) = path.end_with?(".txt")
  end
end
