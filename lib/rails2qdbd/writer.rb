# frozen_string_literal: true

module Rails2qdbd
  # Renders Catalog tables as QuickDBD text, following qdbd's parser rules.
  class Writer
    HEADER = "# Generated by rails2qdbd"
    IDENTIFIER = /\A[A-Za-z0-9_]+\z/
    LIMITED_TYPES = %w[string text binary char varchar citext].freeze
    OPERATORS = { many_to_one: ">-", one_to_one: "-" }.freeze

    # Bare when qdbd accepts it as is, else double-quoted (qdbd has no escape for '"').
    def self.quote_identifier(name)
      name = name.to_s
      name.match?(IDENTIFIER) ? name : %("#{name.tr('"', "'")}")
    end

    # The text after `default=`; nil when there is no default to show.
    def self.format_default(value)
      text = case value
             when nil then return nil
             when Array then "[#{value.map { |v| format_default(v).to_s.delete('"') }.join(',')}]"
             when Hash then value.empty? ? "{}" : value.to_s
             else value.to_s
             end
      text.empty? || text.match?(/[\s#"]/) ? %("#{text.tr('"', "'")}") : text
    end

    # One `# ` line per text line; '#' would end qdbd's comment, so it becomes a full-width ＃.
    def self.comment_lines(text)
      text.to_s.split(/\r?\n/).map { |line| line.split.join(" ").tr("#", "＃") }.reject(&:empty?).map { |line| "# #{line}" }
    end

    # relationships: { [table, column] => Relationship }; notes are extra documentation lines.
    def render_table(table, relationships: {}, table_notes: [], column_notes: {})
      lines = documentation([table.comment, *table_notes, *index_notes(table), *table.checks.map { |c| "check (#{c})" }])
      lines << self.class.quote_identifier(table.name) << "-"
      ordered_columns(table).each do |column|
        lines.concat(documentation(column_docs(column) + column_notes.fetch(column.name, [])))
        lines << column_line(table, column, relationships[[table.name, column.name]])
      end
      lines.join("\n")
    end

    def render_file(tables_text:, inputs:)
      header = ["#{HEADER} #{VERSION} from #{inputs.join(', ')}.",
                "# Re-run the conversion to refresh; manual edits will be overwritten."]
      "#{[header.join("\n"), *tables_text].join("\n\n")}\n"
    end

    private

    def documentation(texts) = texts.compact.flat_map { |text| self.class.comment_lines(text) }

    def ordered_columns(table)
      pk, rest = table.columns.partition { |column| table.primary_key.include?(column.name) }
      pk + rest
    end

    def column_docs(column)
      docs = [column.comment]
      docs << "generated: #{column.generated}" if column.generated
      docs << "enum: #{column.enum_values.join(', ')}" if column.enum_values&.any?
      docs
    end

    def column_line(table, column, relationship)
      pk = table.primary_key.include?(column.name)
      parts = [self.class.quote_identifier(column.name)]
      parts << "PK" if pk
      parts << type(column)
      parts << index_keyword(table, column) unless pk
      parts << "NULL" if column.null && !pk
      default = self.class.format_default(column.default)
      parts << "default=#{default}" if default
      if relationship
        target = "#{self.class.quote_identifier(relationship.to_table)}.#{self.class.quote_identifier(relationship.to_column)}"
        parts << "FK" << OPERATORS.fetch(relationship.cardinality) << target
      end
      parts.compact.join(" ")
    end

    # qdbd types are one token without '=', '#' or '"'.
    def type(column)
      base = column.type.to_s.strip.gsub(/\s+/, "_").tr("=", ":").delete('#"')
      base = "unknown" if base.empty?
      size = if column.precision && column.scale then "(#{column.precision},#{column.scale})"
             elsif column.precision then "(#{column.precision})"
             elsif column.limit && LIMITED_TYPES.include?(base) then "(#{column.limit})"
             end
      "#{base}#{size}#{'[]' if column.array}"
    end

    def index_keyword(table, column)
      single = table.indexes.select { |index| index.single_column? && index.columns.first == column.name }
      if single.any?(&:unique) then "UNIQUE"
      elsif single.any? then "INDEX"
      end
    end

    # Single-column indexes are column keywords, except on a PK column, which takes none: there it is
    # redundant on a one-column key and noted on a composite one.
    def keyword_index?(table, index)
      index.single_column? && (table.primary_key.size == 1 || !table.primary_key.include?(index.columns.first))
    end

    # Indexes qdbd cannot express as a column keyword.
    def index_notes(table)
      table.indexes.reject { |index| keyword_index?(table, index) }.map do |index|
        target = index.expression || index.columns.join(", ")
        note = "#{'unique ' if index.unique}index (#{target})"
        index.where ? "#{note} where #{index.where}" : note
      end
    end
  end
end
