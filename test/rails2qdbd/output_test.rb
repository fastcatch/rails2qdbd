# frozen_string_literal: true

require "test_helper"

class OutputTest < Minitest::Test
  HEADER = "# Generated by rails2qdbd #{Rails2qdbd::VERSION} from db/schema.rb.\n".freeze

  def result(files) = Rails2qdbd::Converter::Result.new(files: files, diagnostics: [], tables: 0, relationships: 0)

  def test_write_directory_replaces_only_generated_files
    Dir.mktmpdir do |dir|
      out = File.join(dir, "schema")
      FileUtils.mkdir_p(out)
      File.write(File.join(out, "old.txt"), "#{HEADER}old\n")
      File.write(File.join(out, "handwritten.txt"), "notes\n-\nid PK int\n")
      File.write(File.join(out, "qdbd.layout.json"), "{}")

      written = Rails2qdbd::Output.write(result("app.txt" => "#{HEADER}a\n"), out)

      assert_equal [File.join(out, "app.txt")], written
      assert_equal %w[app.txt handwritten.txt qdbd.layout.json], Dir.children(out).sort
    end
  end

  def test_write_refuses_to_overwrite_files_it_does_not_own
    Dir.mktmpdir do |dir|
      File.write(File.join(dir, "app.txt"), "notes\n-\nid PK int\n")
      File.write(File.join(dir, "storage.txt"), "")
      error = assert_raises(Rails2qdbd::Error) do
        Rails2qdbd::Output.write(result("app.txt" => "#{HEADER}a\n", "b.txt" => "#{HEADER}b\n", "storage.txt" => "#{HEADER}s\n"), dir)
      end

      assert_equal "not generated by rails2qdbd, left untouched (move or delete them to regenerate): " \
                   "#{dir}/app.txt, #{dir}/storage.txt", error.message
      assert_equal "notes\n-\nid PK int\n", File.read(File.join(dir, "app.txt"))
      refute File.exist?(File.join(dir, "b.txt")), "nothing is written when any destination is not ours"

      single = File.join(dir, "schema.txt")
      File.write(single, "mine\n")
      assert_raises(Rails2qdbd::Error) { Rails2qdbd::Output.write(result("schema.txt" => "#{HEADER}a\n"), single) }
      assert_equal "mine\n", File.read(single)
    end
  end

  def test_write_single_file_creates_parents
    Dir.mktmpdir do |dir|
      path = File.join(dir, "docs/erd/schema.txt")
      Rails2qdbd::Output.write(result("schema.txt" => "#{HEADER}a\n"), path)

      assert_equal "#{HEADER}a\n", File.read(path)
    end
  end

  def test_unchanged_files_are_not_rewritten
    Dir.mktmpdir do |dir|
      Rails2qdbd::Output.write(result("app.txt" => "#{HEADER}a\n"), dir)
      path = File.join(dir, "app.txt")
      File.utime(Time.at(0), Time.at(0), path)

      assert_empty Rails2qdbd::Output.write(result("app.txt" => "#{HEADER}a\n"), dir)
      assert_equal Time.at(0), File.mtime(path)
    end
  end

  def test_stale
    Dir.mktmpdir do |dir|
      out = File.join(dir, "schema")
      fresh = result("a.txt" => "#{HEADER}a\n", "b.txt" => "#{HEADER}b\n")

      assert_equal ["#{out}/a.txt (missing)", "#{out}/b.txt (missing)"], Rails2qdbd::Output.stale(fresh, out)
      Rails2qdbd::Output.write(fresh, out)
      assert_empty Rails2qdbd::Output.stale(fresh, out)

      File.write(File.join(out, "b.txt"), "#{HEADER}changed\n")
      File.write(File.join(out, "c.txt"), "#{HEADER}c\n")
      assert_equal ["#{out}/b.txt (out of date)", "#{out}/c.txt (no longer generated)"], Rails2qdbd::Output.stale(fresh, out)

      File.write(File.join(out, "b.txt"), "handwritten\n")
      assert_equal ["#{out}/b.txt (not generated by rails2qdbd)", "#{out}/c.txt (no longer generated)"],
                   Rails2qdbd::Output.stale(fresh, out)

      single = File.join(dir, "one.txt")
      assert_equal ["#{single} (missing)"], Rails2qdbd::Output.stale(result("schema.txt" => "x\n"), single)
    end
  end
end
