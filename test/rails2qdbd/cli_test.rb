# frozen_string_literal: true

require "test_helper"
require "stringio"

class CLITest < Minitest::Test
  APP = {
    "db/schema.rb" => <<~RUBY,
      ActiveRecord::Schema[8.1].define(version: 1) do
        create_table "tenants" do |t|
        end
        create_table "users" do |t|
          t.bigint "tenant_id"
        end
      end
    RUBY
    "app/models/user.rb" => "class User < ActiveRecord::Base\n  belongs_to :tenant\n  belongs_to :ghost\nend\n",
  }.freeze

  def run_cli(*argv, cwd:)
    out = StringIO.new
    err = StringIO.new
    status = Rails2qdbd::CLI.new(argv, out: out, err: err, cwd: cwd).run
    [status, out.string, err.string]
  end

  def test_prints_to_stdout_by_default
    with_app(APP) do |root|
      status, out, err = run_cli(cwd: root)

      assert_equal 0, status
      assert_includes out, "tenant_id bigint NULL FK >- tenants.id"
      assert_equal "app/models/user.rb:3: warning: User belongs_to :ghost: class Ghost not found, skipped\n", err
    end
  end

  def test_app_root_argument_and_output_relative_to_cwd
    with_app(APP) do |root|
      Dir.mktmpdir do |elsewhere|
        status, out, = run_cli(root, "-o", "erd/schema.txt", cwd: elsewhere)

        assert_equal 0, status
        assert_match(/wrote 1 file.*2 tables, 1 relationship/, out)
        text = File.read(File.join(elsewhere, "erd/schema.txt"))
        assert_includes text, "from db/schema.rb, app/models."
      end
    end
  end

  def test_output_directory
    with_app(APP) do |root|
      status, = run_cli("-o", "schema", "-q", cwd: root)

      assert_equal 0, status
      assert_equal ["schema.txt"], Dir.children(File.join(root, "schema"))
    end
  end

  def test_handwritten_output_is_not_overwritten
    with_app(APP) do |root|
      FileUtils.mkdir_p(File.join(root, "schema"))
      File.write(File.join(root, "schema/schema.txt"), "notes\n-\nid PK int\n")
      status, _, err = run_cli("-o", "schema", "-q", cwd: root)

      assert_equal 1, status
      assert_includes err, "rails2qdbd: not generated by rails2qdbd, left untouched"
      assert_equal "notes\n-\nid PK int\n", File.read(File.join(root, "schema/schema.txt"))
    end
  end

  def test_check
    with_app(APP) do |root|
      assert_equal 2, run_cli("--check", cwd: root).first

      status, _, err = run_cli("--check", "-o", "schema", "-q", cwd: root)
      assert_equal 1, status
      assert_includes err, "out of date: #{File.join(root, 'schema/schema.txt')} (missing)"

      run_cli("-o", "schema", "-q", cwd: root)
      status, out, = run_cli("--check", "-o", "schema", "-q", cwd: root)
      assert_equal [0, "up to date\n"], [status, out]
    end
  end

  def test_no_models_and_exclude
    with_app(APP) do |root|
      _, out, err = run_cli("--no-models", "--exclude", "tenants", cwd: root)

      refute_includes out, "tenants\n-"
      refute_includes out, "FK"
      assert_empty err
    end
  end

  def test_schema_and_models_options
    with_app(APP.transform_keys { |k| k.sub("db/schema.rb", "db/main_schema.rb").sub("app/models", "lib/models") }) do |root|
      status, out, = run_cli("--schema", "db/main_schema.rb", "--models", "lib/models", "-q", cwd: root)

      assert_equal 0, status
      assert_includes out, "from db/main_schema.rb, lib/models."
    end
  end

  def test_config_option
    with_app(APP.merge("conf/erd.yml" => "exclude: [users]\n")) do |root|
      _, out, = run_cli("--config", "conf/erd.yml", "-q", cwd: root)

      refute_includes out, "users\n-"
    end
  end

  def test_missing_schema
    with_app(APP.slice("app/models/user.rb")) do |root|
      status, out, err = run_cli(cwd: root)

      assert_equal [1, ""], [status, out]
      assert_equal "rails2qdbd: schema file not found: db/schema.rb\n", err
    end
  end

  def test_schema_errors_prevent_writing
    with_app(APP.merge("db/schema.rb" => "create_table \"a\" do |t|\n")) do |root|
      status, _, err = run_cli("-o", "schema", cwd: root)

      assert_equal 1, status
      assert_match(/db\/schema.rb:\d+: error: syntax error/, err)
      refute File.exist?(File.join(root, "schema"))
    end
  end

  def test_version_help_and_bad_options
    assert_equal [0, "rails2qdbd #{Rails2qdbd::VERSION}\n"], run_cli("--version", cwd: Dir.pwd).first(2)
    status, out, = run_cli("--help", cwd: Dir.pwd)
    assert_equal 0, status
    assert_includes out, "Usage: rails2qdbd [APP_ROOT] [options]"

    status, _, err = run_cli("--bogus", cwd: Dir.pwd)
    assert_equal 2, status
    assert_includes err, "invalid option: --bogus"
  end

  def test_executable_runs
    with_app(APP) do |root|
      out, status = Open3.capture2(RbConfig.ruby, "-I", File.join(QdbdHelpers::ROOT, "lib"),
                                      File.join(QdbdHelpers::ROOT, "exe/rails2qdbd"), root, "-q")

      assert status.success?
      assert_includes out, "users\n-"
    end
  end
end
