# frozen_string_literal: true

require "test_helper"

class ConverterTest < Minitest::Test
  SCHEMA = <<~RUBY
    ActiveRecord::Schema[8.1].define(version: 1) do
      create_table "active_storage_blobs" do |t|
        t.string "key", null: false
      end
      create_table "active_storage_attachments" do |t|
        t.bigint "blob_id", null: false
      end
      create_table "tenants" do |t|
        t.string "name", null: false
      end
      create_table "users" do |t|
        t.bigint "tenant_id", null: false
        t.bigint "avatar_blob_id"
      end
      add_foreign_key "active_storage_attachments", "active_storage_blobs", column: "blob_id"
      add_foreign_key "users", "active_storage_blobs", column: "avatar_blob_id"
    end
  RUBY

  APP = {
    "db/schema.rb" => SCHEMA,
    "app/models/application_record.rb" => "class ApplicationRecord < ActiveRecord::Base\n  primary_abstract_class\nend\n",
    "app/models/user.rb" => "class User < ApplicationRecord\n  belongs_to :tenant\n  belongs_to :ghost\nend\n",
  }.freeze

  def convert(files = APP, **overrides)
    with_app(files) { |root| return Rails2qdbd.convert(root, **overrides) }
  end

  def test_single_file
    result = convert

    assert_equal ["schema.txt"], result.files.keys
    text = result.files["schema.txt"]
    assert_includes text, "# Generated by rails2qdbd #{Rails2qdbd::VERSION} from db/schema.rb, app/models."
    assert_includes text, "tenant_id bigint FK >- tenants.id"
    assert_equal %w[active_storage_attachments active_storage_blobs tenants users], text.scan(/^(\w+)\n-$/).flatten
    assert_equal ["app/models/user.rb:3: warning: User belongs_to :ghost: class Ghost not found, skipped"], result.diagnostics.map(&:to_s)
    assert_equal [4, 3], [result.tables, result.relationships]
  end

  def test_excluded_tables_and_notes
    text = convert(exclude: ["active_storage_*"]).files["schema.txt"]

    refute_includes text, "active_storage_blobs\n-"
    assert_includes text, "# references active_storage_blobs (excluded)\navatar_blob_id bigint NULL\n"
  end

  def test_groups_split_into_files_for_directory_output
    files = APP.merge(".rails2qdbd.yml" => "groups:\n  storage: [\"active_storage_*\"]\n")
    split = convert(files, output: "schema/")

    assert_equal %w[app.txt storage.txt], split.files.keys
    assert_includes split.files["app.txt"], "users\n-"
    assert_includes split.files["storage.txt"], "active_storage_blobs\n-"

    assert_equal ["schema.txt"], convert(files, output: "erd.txt").files.keys
    assert_equal ["schema.txt"], convert(APP, output: "schema/").files.keys
  end

  def test_no_tables_still_writes_the_header
    header = "# Generated by rails2qdbd #{Rails2qdbd::VERSION} from db/schema.rb, app/models.\n" \
             "# Re-run the conversion to refresh; manual edits will be overwritten.\n"

    assert_equal({ "schema.txt" => header }, convert(exclude: ["*"]).files)
    assert_equal({ "schema.txt" => header }, convert(exclude: ["*"], output: "schema/").files)
  end

  def test_schema_only
    result = convert(models: false)

    refute_includes result.files["schema.txt"], "FK >- tenants.id"
    assert_includes result.files["schema.txt"], "from db/schema.rb."
    assert_empty result.diagnostics
  end

  def test_missing_models_directory_warns
    result = convert(APP.slice("db/schema.rb"))

    assert_equal ["warning: models directory not found: app/models (relationships come from the schema only)"],
                 result.diagnostics.map(&:to_s)
  end

  def test_project_inflections_are_used
    files = APP.merge(
      "db/schema.rb" => SCHEMA.sub('create_table "tenants"', 'create_table "tenantz"'),
      "config/initializers/inflections.rb" => "ActiveSupport::Inflector.inflections(:en) do |i|\n  i.irregular \"tenant\", \"tenantz\"\nend\n",
    )

    assert_includes convert(files).files["schema.txt"], "tenant_id bigint FK >- tenantz.id"
  end

  def test_output_is_deterministic_and_valid
    first = convert.files
    assert_equal first, convert.files
    Dir.mktmpdir do |dir|
      File.write(File.join(dir, "schema.txt"), first["schema.txt"])
      assert_qdbd_valid(dir)
    end
  end
end
